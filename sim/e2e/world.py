    def group(name, kind, members=None, extra=()):
        out = ["- name: %s" % yaml_str(name), "  type: %s" % kind]
        out += ["  %s" % item for item in extra]
        if members:
            out += ["  proxies:"] + ["  - %s" % yaml_str(m) for m in members]
        return out
    lines += group("AI 台湾家宽线路", "select", TW[:3], ("interrupt-exist-connections: false", "disable-udp: true"))
