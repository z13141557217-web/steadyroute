def build(home):
    home = pathlib.Path(home)
    (home / "profiles").mkdir(parents=True)
    (home / "ruleset").mkdir()
    (home / "profiles.yaml").write_text(PROFILES, encoding="utf-8")
    (home / "profiles" / "GgroupE2E.yaml").write_text(GROUPS_EXT, encoding="utf-8")
    (home / "profiles" / "RrulesE2E.yaml").write_text(RULES_EXT, encoding="utf-8")
    (home / "clash-verge.yaml").write_text(runtime(), encoding="utf-8")
    for name, entries in RULESETS.items():
        (home / "ruleset" / name).write_text("payload:\n" + "".join("  - '%s'\n" % e for e in entries), encoding="utf-8")
    return home
